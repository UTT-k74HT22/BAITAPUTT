package org.example.repository;

import org.example.config.DatabaseConfig;
import org.example.exception.DataAccessException;
import java.sql.*;
import java.util.*;
import java.util.function.Function;
import java.util.logging.Level;
import java.util.logging.Logger;

/**
 * BaseRepository cung cấp các phương thức chung để tương tác với cơ sở dữ liệu.
 *
 * <p>Mục tiêu: giảm lặp code JDBC thuần (Connection/PreparedStatement/ResultSet),
 * chuẩn hóa việc map dữ liệu (RowMapper), execute update/insert, và hỗ trợ transaction khi cần.</p>
 *
 * <p>Lưu ý: JDBC (java.sql) KHÔNG có sẵn queryForList/queryForObject dạng tiện ích.
 * Bạn đang xây một “mini JdbcTemplate”. JDBC chỉ cung cấp API mức thấp:
 * Connection, PreparedStatement, ResultSet, getGeneratedKeys, batch, transaction,...</p>
 */
public abstract class BaseRepository {

    private static final Logger log = Logger.getLogger(BaseRepository.class.getName());

    @FunctionalInterface
    protected interface PreparedStatementSetter {
        void setValues(PreparedStatement preparedStatement) throws SQLException;
    }

    @FunctionalInterface
    protected interface ResultSetMapper<T> {
        T map(ResultSet resultSet) throws SQLException;
    }

    /**
     * Chuẩn hóa việc wrap SQLException + log kèm SQL để dễ debug.
     *
     * @param action hành động đang thực hiện (Query/Update/Insert/Exists/Transaction...)
     * @param sql câu SQL gây lỗi
     * @param e SQLException gốc
     * @return DataAccessException
     */
    private DataAccessException dbError(String action, String sql, SQLException e) {
        // Tránh log params trực tiếp để không lộ dữ liệu nhạy cảm.
        log.log(Level.SEVERE, action + " failed. SQL=" + sql + " | " + e.getMessage(), e);
        return new DataAccessException(action + " failed. SQL=" + sql, e);
    }

    /**
     * Helper nội bộ: tạo PreparedStatement, set params (nếu có), rồi chạy handler.
     *
     * <p>autoGeneratedKeys:
     * - Statement.NO_GENERATED_KEYS: statement thường
     * - Statement.RETURN_GENERATED_KEYS: dùng cho INSERT muốn lấy generated key</p>
     */
    private <T> T withPreparedStatement(
            Connection conn,
            String sql,
            int autoGeneratedKeys,
            PreparedStatementSetter setter,
            Function<PreparedStatement, T> handler
    ) throws SQLException {
        try (PreparedStatement ps =
                     (autoGeneratedKeys == Statement.NO_GENERATED_KEYS)
                             ? conn.prepareStatement(sql)
                             : conn.prepareStatement(sql, autoGeneratedKeys)) {

            if (setter != null) {
                setter.setValues(ps);
            }
            return handler.apply(ps);
        }
    }

    // ======================================================================
    // QUERY
    // ======================================================================

    /**
     * Execute query và trả về Optional<T>
     */
    protected <T> Optional<T> queryForObject(String sql, PreparedStatementSetter setter, ResultSetMapper<T> mapper) {
        Objects.requireNonNull(sql, "sql must not be null");
        Objects.requireNonNull(mapper, "mapper must not be null");

        try (Connection connection = DatabaseConfig.getConnection()) {
            return queryForObject(connection, sql, setter, mapper);
        } catch (SQLException e) {
            throw dbError("Query for object", sql, e);
        }
    }

    /**
     * Execute query và trả về Optional<T> (không có parameters).
     *
     * @param sql câu query
     * @param mapper mapper map 1 row thành T
     */
    protected <T> Optional<T> queryForObject(String sql, ResultSetMapper<T> mapper) {
        return queryForObject(sql, ps -> {}, mapper);
    }

    /**
     * Execute query và trả về Optional<T> với Connection truyền vào (phục vụ transaction).
     *
     * @param conn connection đã có (có thể đang ở transaction)
     * @param sql câu query
     * @param setter set params cho PreparedStatement (có thể null)
     * @param mapper mapper map 1 row thành T
     */
    protected <T> Optional<T> queryForObject(Connection conn, String sql, PreparedStatementSetter setter, ResultSetMapper<T> mapper)
            throws SQLException {

        try {
            return withPreparedStatement(conn, sql, Statement.NO_GENERATED_KEYS, setter, ps -> {
                try (ResultSet rs = ps.executeQuery()) {
                    if (rs.next()) {
                        return Optional.ofNullable(mapper.map(rs));
                    }
                    return Optional.empty();
                } catch (SQLException ex) {
                    throw new RuntimeException(ex);
                }
            });
        } catch (RuntimeException re) {
            if (re.getCause() instanceof SQLException se) throw se;
            throw re;
        }
    }

    /**
     * Execute query và trả về T, nếu không tìm thấy thì ném ra RuntimeException
     */
    protected <T> T queryForEntity(String sql, PreparedStatementSetter setter, ResultSetMapper<T> mapper) {
        Optional<T> optionalEntity = queryForObject(sql, setter, mapper);
        return optionalEntity.orElseThrow(() -> new NoSuchElementException("Entity not found"));
    }

    /**
     * Execute query và trả về T, nếu không tìm thấy thì ném ra exception với message tùy biến.
     *
     * @param sql câu query
     * @param setter set params
     * @param mapper mapper map row -> entity
     * @param notFoundMessage thông báo khi không tìm thấy
     * @return entity bắt buộc phải có
     */
    protected <T> T queryForEntity(String sql, PreparedStatementSetter setter, ResultSetMapper<T> mapper, String notFoundMessage) {
        return queryForObject(sql, setter, mapper)
                .orElseThrow(() -> new NoSuchElementException(
                        notFoundMessage != null ? notFoundMessage : "Entity not found"
                ));
    }

    /**
     * Execute query và trả về List<T>
     */
    protected <T> List<T> queryForList(String sql, PreparedStatementSetter setter, ResultSetMapper<T> mapper) {
        Objects.requireNonNull(sql, "sql must not be null");
        Objects.requireNonNull(mapper, "mapper must not be null");

        try (Connection connection = DatabaseConfig.getConnection()) {
            return queryForList(connection, sql, setter, mapper);
        } catch (SQLException e) {
            throw dbError("Query for list", sql, e);
        }
    }

    /**
     * Execute query và trả về List<T> với Connection truyền vào (phục vụ transaction).
     *
     * @param conn connection đã có (có thể đang ở transaction)
     * @param sql câu query
     * @param setter set params (có thể null)
     * @param mapper mapper map row -> T
     */
    protected <T> List<T> queryForList(Connection conn, String sql, PreparedStatementSetter setter, ResultSetMapper<T> mapper)
            throws SQLException {

        try {
            return withPreparedStatement(conn, sql, Statement.NO_GENERATED_KEYS, setter, ps -> {
                List<T> results = new ArrayList<>();
                try (ResultSet rs = ps.executeQuery()) {
                    while (rs.next()) {
                        results.add(mapper.map(rs));
                    }
                    return results;
                } catch (SQLException ex) {
                    throw new RuntimeException(ex);
                }
            });
        } catch (RuntimeException re) {
            if (re.getCause() instanceof SQLException se) throw se;
            throw re;
        }
    }

    /**
     * Execute query đơn giản không cần parameters
     */
    protected <T> List<T> queryForList(String sql, ResultSetMapper<T> mapper) {
        return queryForList(sql, ps -> {}, mapper);
    }

    /**
     * Execute query và mong đợi chỉ 0 hoặc 1 row.
     * Nếu có nhiều hơn 1 row, ném exception để bắt lỗi logic query sớm.
     *
     * @param sql câu query
     * @param setter set params
     * @param mapper mapper map row -> T
     * @return Optional<T>
     */
    protected <T> Optional<T> queryForSingleRow(String sql, PreparedStatementSetter setter, ResultSetMapper<T> mapper) {
        Objects.requireNonNull(sql, "sql must not be null");
        Objects.requireNonNull(mapper, "mapper must not be null");

        try (Connection conn = DatabaseConfig.getConnection()) {
            return queryForSingleRow(conn, sql, setter, mapper);
        } catch (SQLException e) {
            throw dbError("Query for single row", sql, e);
        }
    }

    /**
     * Execute query (0/1 row) với Connection truyền vào (phục vụ transaction).
     */
    protected <T> Optional<T> queryForSingleRow(Connection conn, String sql, PreparedStatementSetter setter, ResultSetMapper<T> mapper)
            throws SQLException {

        try {
            return withPreparedStatement(conn, sql, Statement.NO_GENERATED_KEYS, setter, ps -> {
                try (ResultSet rs = ps.executeQuery()) {
                    if (!rs.next()) return Optional.empty();

                    T value = mapper.map(rs);

                    // strict: nếu có row thứ 2 -> throw để bắt bug query
                    if (rs.next()) {
                        throw new IllegalStateException("Expected 0/1 row but got multiple rows. SQL=" + sql);
                    }
                    return Optional.ofNullable(value);
                } catch (SQLException ex) {
                    throw new RuntimeException(ex);
                }
            });
        } catch (RuntimeException re) {
            if (re.getCause() instanceof SQLException se) throw se;
            throw re;
        }
    }

    // ======================================================================
    // UPDATE / DELETE
    // ======================================================================

    /**
     * Execute update (INSERT/UPDATE/DELETE) và trả về số rows affected
     */
    protected int executeUpdate(String sql, PreparedStatementSetter setter) {
        Objects.requireNonNull(sql, "sql must not be null");

        try (Connection conn = DatabaseConfig.getConnection()) {
            return executeUpdate(conn, sql, setter);
        } catch (SQLException e) {
            throw dbError("Execute update", sql, e);
        }
    }

    /**
     * Execute update (không cần parameters) và trả về số rows affected.
     *
     * @param sql câu SQL update/delete/insert
     */
    protected int executeUpdate(String sql) {
        return executeUpdate(sql, ps -> {});
    }

    /**
     * Execute update với Connection truyền vào (phục vụ transaction) và trả về số rows affected.
     *
     * @param conn connection đang dùng
     * @param sql câu SQL
     * @param setter set params (có thể null)
     */
    protected int executeUpdate(Connection conn, String sql, PreparedStatementSetter setter) throws SQLException {
        try {
            return withPreparedStatement(conn, sql, Statement.NO_GENERATED_KEYS, setter, ps -> {
                try {
                    return ps.executeUpdate();
                } catch (SQLException ex) {
                    throw new RuntimeException(ex);
                }
            });
        } catch (RuntimeException re) {
            if (re.getCause() instanceof SQLException se) throw se;
            throw re;
        }
    }

    /**
     * Execute update và nếu không có hàng nào bị ảnh hưởng thì ném ra RuntimeException
     */
    protected void executeUpdateOrThrow(String sql, PreparedStatementSetter setter, String notFoundMessage) {
        int rowsAffected = executeUpdate(sql, setter);
        if (rowsAffected == 0) {
            throw new NoSuchElementException(notFoundMessage != null ? notFoundMessage : "No rows affected");
        }
    }

    // ======================================================================
    // INSERT
    // ======================================================================

    /**
     * Execute insert và trả về ID của bản ghi mới tạo
     *
     * <p><b>Quan trọng:</b> để lấy generated keys đúng chuẩn JDBC,
     * cần prepareStatement(sql, Statement.RETURN_GENERATED_KEYS).</p>
     *
     * @param sql câu insert
     * @param setter set params (có thể null)
     * @return generated id (long)
     */
    protected long executeInsertAndReturnId(String sql, PreparedStatementSetter setter) {
        Objects.requireNonNull(sql, "sql must not be null");

        try (Connection conn = DatabaseConfig.getConnection()) {
            return executeInsertAndReturnId(conn, sql, setter);
        } catch (SQLException e) {
            throw dbError("Execute insert", sql, e);
        }
    }

    /**
     * Execute insert và trả về ID với Connection truyền vào (phục vụ transaction).
     *
     * @param conn connection đang dùng
     * @param sql câu insert
     * @param setter set params (có thể null)
     * @return generated id (long)
     */
    protected long executeInsertAndReturnId(Connection conn, String sql, PreparedStatementSetter setter) throws SQLException {
        try {
            return withPreparedStatement(conn, sql, Statement.RETURN_GENERATED_KEYS, setter, ps -> {
                try {
                    int rows = ps.executeUpdate();
                    if (rows == 0) {
                        throw new IllegalStateException("Insert affected 0 rows. SQL=" + sql);
                    }
                    try (ResultSet generatedKeys = ps.getGeneratedKeys()) {
                        if (generatedKeys.next()) {
                            return generatedKeys.getLong(1);
                        }
                        throw new IllegalStateException("No generated keys returned. SQL=" + sql);
                    }
                } catch (SQLException ex) {
                    throw new RuntimeException(ex);
                }
            });
        } catch (RuntimeException re) {
            if (re.getCause() instanceof SQLException se) throw se;
            throw re;
        }
    }

    // ======================================================================
    // EXISTS
    // ======================================================================

    /**
     * Check existence (trả về boolean)
     *
     * <p>Khuyến nghị SQL nên viết tối ưu:
     * <code>SELECT 1 FROM table WHERE ... LIMIT 1</code> (MySQL/Postgres)
     * hoặc <code>SELECT EXISTS(...)</code>.</p>
     */
    protected boolean exists(String sql, PreparedStatementSetter setter) {
        Objects.requireNonNull(sql, "sql must not be null");

        try (Connection conn = DatabaseConfig.getConnection()) {
            return exists(conn, sql, setter);
        } catch (SQLException e) {
            throw dbError("Exists", sql, e);
        }
    }

    /**
     * Check existence với Connection truyền vào (phục vụ transaction).
     *
     * @param conn connection đang dùng
     * @param sql câu SQL
     * @param setter set params (có thể null)
     */
    protected boolean exists(Connection conn, String sql, PreparedStatementSetter setter) throws SQLException {
        try {
            return withPreparedStatement(conn, sql, Statement.NO_GENERATED_KEYS, setter, ps -> {
                try (ResultSet rs = ps.executeQuery()) {
                    return rs.next();
                } catch (SQLException ex) {
                    throw new RuntimeException(ex);
                }
            });
        } catch (RuntimeException re) {
            if (re.getCause() instanceof SQLException se) throw se;
            throw re;
        }
    }

    // ======================================================================
    // TRANSACTION (OPTIONAL)
    // ======================================================================

    /**
     * Chạy một khối logic trong Transaction (commit/rollback tự động).
     *
     * <p>Dùng khi cần nhiều thao tác DB chung 1 transaction:
     * insert user + insert role + update log... Nếu lỗi sẽ rollback.</p>
     *
     * <pre>
     * return inTransaction(conn -> {
     *     long id = executeInsertAndReturnId(conn, sqlInsert, setter);
     *     executeUpdate(conn, sqlUpdate, setter2);
     *     return id;
     * });
     * </pre>
     *
     * @param callback callback nhận Connection dùng chung transaction
     * @return kết quả trả về từ callback
     */
    protected <T> T inTransaction(TransactionCallback<T> callback) {
        Objects.requireNonNull(callback, "callback must not be null");

        try (Connection conn = DatabaseConfig.getConnection()) {
            boolean oldAutoCommit = conn.getAutoCommit();
            conn.setAutoCommit(false);

            try {
                T result = callback.doInTransaction(conn);
                conn.commit();
                return result;
            } catch (Exception ex) {
                try {
                    conn.rollback();
                } catch (SQLException rollbackEx) {
                    log.log(Level.SEVERE, "Rollback failed: " + rollbackEx.getMessage(), rollbackEx);
                }
                throw ex;
            } finally {
                try {
                    conn.setAutoCommit(oldAutoCommit);
                } catch (SQLException ignore) {
                }
            }
        } catch (SQLException e) {
            throw new DataAccessException("Transaction failed", e);
        }
    }

    /**
     * Functional interface cho transaction callback.
     * Cho phép throws SQLException để tiện viết code JDBC.
     */
    @FunctionalInterface
    protected interface TransactionCallback<T> {
        T doInTransaction(Connection conn) throws SQLException;
    }

    // ======================================================================
    // PARAMS HELPER (OPTIONAL)
    // ======================================================================

    /**
     * Tạo PreparedStatementSetter nhanh từ danh sách params.
     *
     * <p>Tận dụng API JDBC có sẵn: {@link PreparedStatement#setObject(int, Object)}.</p>
     *
     * <pre>
     * queryForList("SELECT * FROM users WHERE username = ?",
     *     params(username),
     *     rs -> mapUser(rs)
     * );
     * </pre>
     *
     * @param params danh sách params theo thứ tự dấu ?
     * @return PreparedStatementSetter
     */
    protected PreparedStatementSetter params(Object... params) {
        return ps -> {
            if (params == null) return;
            for (int i = 0; i < params.length; i++) {
                ps.setObject(i + 1, params[i]);
            }
        };
    }
}
